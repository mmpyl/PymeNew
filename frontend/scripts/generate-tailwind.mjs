import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { compile } from 'tailwindcss';

const require = createRequire(import.meta.url);
const frontendRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = dirname(frontendRoot);
const tailwindRoot = dirname(require.resolve('tailwindcss/package.json'));
const outputFile = join(frontendRoot, 'app', 'generated-tailwind.css');

const sourceFiles = [
  'app/layout.tsx',
  'app/page.tsx',
  'app/login/page.tsx',
  'app/register/page.tsx',
  'app/dashboard/page.tsx',
  'components/ProtectedRoute.tsx',
  'contexts/AuthContext.tsx',
];

const dynamicCandidates = [
  'bg-green-50',
  'bg-red-50',
  'text-green-700',
  'text-red-700',
];

const stylesheetFiles = new Map([
  ['tailwindcss', 'index.css'],
  ['tailwindcss/theme', 'theme.css'],
  ['tailwindcss/preflight', 'preflight.css'],
  ['tailwindcss/utilities', 'utilities.css'],
]);

function collectCandidates(source) {
  const candidates = new Set(dynamicCandidates);
  const classNamePattern = /className=(?:"([^"]*)"|'([^']*)'|\{`([\s\S]*?)`\})/g;
  let match;

  while ((match = classNamePattern.exec(source))) {
    const classValue = match[1] ?? match[2] ?? match[3] ?? '';
    for (const token of classValue.split(/\s+/)) {
      const candidate = token.trim();

      if (!candidate || candidate.includes('${')) {
        continue;
      }

      candidates.add(candidate);
    }
  }

  return candidates;
}

async function loadStylesheet(id) {
  const file = stylesheetFiles.get(id);

  if (!file) {
    throw new Error(`Unsupported Tailwind stylesheet import: ${id}`);
  }

  const filename = join(tailwindRoot, file);
  return {
    content: await readFile(filename, 'utf8'),
    base: dirname(filename),
  };
}

const allCandidates = new Set();

for (const file of sourceFiles) {
  const content = await readFile(join(frontendRoot, file), 'utf8');
  for (const candidate of collectCandidates(content)) {
    allCandidates.add(candidate);
  }
}

const compiler = await compile('@import "tailwindcss";', {
  base: repoRoot,
  loadStylesheet,
});

const css = compiler.build([...allCandidates].sort());
const banner = '/* This file is generated by scripts/generate-tailwind.mjs. Do not edit by hand. */\n';
await writeFile(outputFile, `${banner}${css}`);

console.log(`Generated ${outputFile.replace(`${repoRoot}/`, '')} with ${allCandidates.size} Tailwind candidates.`);
